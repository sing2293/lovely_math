#!/usr/bin/env node
// Seals the site's content and worked solutions, per language, behind the sign-in.
//
//   SITE_NAME='…' SITE_PASSWORD='…' node tools/seal-site.mjs \
//     en=../vault-source/content.json,../vault-source/solutions.json \
//     tr=../vault-source/content_tr.json,../vault-source/solutions_tr.json
//
// Each content file is the full site content for that language (families, walkthroughs, cards,
// tests, plan); each solutions file maps solution ids to HTML. Keep them all OUTSIDE the
// repository: only the ciphertext in assets/js/secure-data.js is committed.
import { readFileSync, writeFileSync } from 'node:fs';
import { webcrypto as crypto } from 'node:crypto';

const args = process.argv.slice(2);
const outArg = args.find((a) => a.startsWith('--out='));
const out = outArg ? outArg.slice(6) : 'assets/js/secure-data.js';
const langs = args.filter((a) => /^[a-z]{2}=/.test(a)).map((a) => {
  const [code, files] = a.split('=');
  const [contentPath, solutionsPath] = files.split(',');
  return { code, contentPath, solutionsPath };
});
const { SITE_NAME, SITE_PASSWORD } = process.env;
if (!langs.length || !langs.some((l) => l.code === 'en') || !SITE_NAME || !SITE_PASSWORD) {
  console.error("Usage: SITE_NAME='…' SITE_PASSWORD='…' node tools/seal-site.mjs en=content.json,solutions.json [tr=content_tr.json,solutions_tr.json] [--out=file.js]");
  process.exit(1);
}
// Must match secretOf() in assets/js/auth.js.
const secret = SITE_NAME.trim().toLowerCase() + ':' + SITE_PASSWORD.toLowerCase().replace(/\s+/g, '');

const enc = new TextEncoder();
const b64 = (buf) => Buffer.from(buf).toString('base64');
const salt = crypto.getRandomValues(new Uint8Array(16));
const iter = 250000;
const base = await crypto.subtle.importKey('raw', enc.encode(secret), 'PBKDF2', false, ['deriveKey']);
const key = await crypto.subtle.deriveKey(
  { name: 'PBKDF2', salt, iterations: iter, hash: 'SHA-256' },
  base,
  { name: 'AES-GCM', length: 256 },
  false,
  ['encrypt']
);
async function seal(text) {
  const iv = crypto.getRandomValues(new Uint8Array(12));
  const ct = await crypto.subtle.encrypt({ name: 'AES-GCM', iv }, key, enc.encode(text));
  return { iv: b64(iv), ct: b64(ct) };
}

const sealed = { v: 3, kdf: 'PBKDF2-SHA256', iter, salt: b64(salt), check: await seal('lovely-math-ok'), langs: {} };
for (const { code, contentPath, solutionsPath } of langs) {
  const content = readFileSync(contentPath, 'utf8');
  JSON.parse(content); // fail early on a broken file
  const solutions = solutionsPath ? JSON.parse(readFileSync(solutionsPath, 'utf8')) : {};
  const pack = { content: await seal(content), items: {} };
  for (const [id, html] of Object.entries(solutions)) pack.items[id] = await seal(html);
  sealed.langs[code] = pack;
  console.log(`${code}: content + ${Object.keys(solutions).length} solutions`);
}

writeFileSync(
  out,
  `/* Generated by tools/seal-site.mjs: the site's encrypted content and solutions. Do not edit by hand. */\n` +
    `window.LOVELY_SEALED = ${JSON.stringify(sealed)};\n`
);
console.log(`Sealed into ${out}`);
